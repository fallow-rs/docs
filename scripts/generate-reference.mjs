/**
 * Sets the frontmatter fields that the generator owns (`title` and
 * `description`) and keeps every other line of the page.
 */
export const setFrontmatter = (text, fields, file) => {
  const eol = text.includes("\r\n") ? "\r\n" : "\n";
  const block = text.match(/^---\r?\n([\s\S]*?)\r?\n---(?=\r?\n|$)/u);
  if (block === null) {
    throw new Error(`${file}:1: the page has no frontmatter.`);
  }
  const lines = block[1].split(/\r?\n/u);
  for (const [key, value] of Object.entries(fields).reverse()) {
    const line = `${key}: ${yamlString(value)}`;
    const index = lines.findIndex((entry) => entry.startsWith(`${key}:`));
    if (index === -1) {
      lines.unshift(line);
    } else {
      lines[index] = line;
    }
  }
  return `---${eol}${lines.join(eol)}${eol}---${text.slice(block[0].length)}`;
};

/** The page of a rule after generation: a new page, or the old page with a new block and frontmatter. */
export const updateRulePage = (contract, issue, existing, file, configLink) => {
  if (existing === undefined) {
    return newRulePage(contract, issue, configLink);
  }
  const blocks = findBlocks(existing, file).filter((block) => block.type === "rule");
  if (blocks.length !== 1 || blocks[0].argument !== issue.id) {
    throw new Error(`${file}:1: a rule page needs exactly one block ${startMarker("rule", issue.id)}.`);
  }
  const withFields = setFrontmatter(existing, { title: ruleTitle(issue), description: ruleDescription(issue) }, file);
  return replaceBlocks(withFields, (block) => renderBlock(contract, block, { configLink }), file);
};

