// Anchors of the old explanation pages that name a section about several
// issue types or about a metric. They map to `null`, and the index pages keep
// a section for each.
export const SECTION_ANCHORS = new Set(["complexity-metrics", "coverage-gaps", "coverage-intelligence", "file-health-scores", "maintainability-index-mi"]);

const anchorOfUrl = (url, page) => {
  const match = (url ?? "").match(/\/docs\/([^#]+?)\/?#([\w-]+)$/u);
  return match !== null && match[1] === page ? match[2] : null;
};

/** The singular form of a hyphenated plural, for example `unused-dependencies` to `unused-dependency`. */
export const singular = (word) =>
  word.replace(/ies$/u, "y").replace(/(?<=s)es$/u, "").replace(/(?<!s)s$/u, "");

/**
 * Maps each anchor of the old explanation pages to the rule page that covers
 * it. The anchors come from the released links and from the `docs_url` of
 * each issue type. An anchor maps to the issue type whose id is the anchor
 * or its singular, else to the only issue type whose config key or docs
 * anchor is the anchor, else to the only issue type whose `docs_url` names
 * it, else to `null`.
 */
export const buildRuleAnchors = (contract, inbound) => {
  const result = {};
  for (const page of ANCHOR_PAGES) {
    const anchors = new Set();
    for (const link of inbound.links) {
      const [path, anchor] = link.split("#");
      if (path === page && anchor) {
        anchors.add(anchor);
      }
    }
    for (const issue of contract.issue_types) {
      const anchor = anchorOfUrl(issue.docs_url, page);
      if (anchor !== null) {
        anchors.add(anchor);
      }
    }
    const map = {};
    for (const anchor of [...anchors].sort()) {
      if (SECTION_ANCHORS.has(anchor)) {
        map[anchor] = null;
        continue;
      }
      const forms = new Set([anchor, singular(anchor)]);
      const exact = contract.issue_types.filter((issue) => forms.has(issue.id));
      const named = contract.issue_types.filter((issue) => [issue.config_key, issue.summary_docs_anchor].some((name) => name === anchor));
      const linked = contract.issue_types.filter((issue) => anchorOfUrl(issue.docs_url, page) === anchor);
      const pick = [exact, named, linked].find((candidates) => candidates.length === 1)?.[0] ?? null;
      map[anchor] = pick === null ? null : `rules/${pick.id}`;
    }
    result[page] = map;
  }
  return result;
};

