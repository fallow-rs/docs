// Markers

const START_MARKER = /^[ \t]*\{\/\*[ \t]*generated:start[ \t]+([a-z][a-z-]*)(?:[ \t]+([^*]*?))?[ \t]*\*\/\}[ \t]*\r?$/u;
const END_MARKER = /^[ \t]*\{\/\*[ \t]*generated:end[ \t]*\*\/\}[ \t]*\r?$/u;
const ANY_MARKER = /^[ \t]*\{\/\*[ \t]*generated:/u;

/** The marker line that opens a block of one type. */
export const startMarker = (type, argument = "") =>
  `{/* generated:start ${type}${argument === "" ? "" : ` ${argument}`} */}`;

export const END = "{/* generated:end */}";

const lineAt = (text, offset) => text.slice(0, offset).split("\n").length;

/**
 * The marked blocks of a file: the type, the argument, the line of the start
 * marker, and the offsets of the content between the two marker lines.
 * Throws with the file and the line when a marker has no partner or when a
 * block opens inside another block.
 */
export const findBlocks = (text, file) => {
  const markers = [];
  for (const line of text.matchAll(/^.*$/gmu)) {
    if (!ANY_MARKER.test(line[0])) {
      continue;
    }
    const start = line[0].match(START_MARKER);
    const position = { index: line.index, end: line.index + line[0].replace(/\r$/u, "").length };
    if (start !== null) {
      markers.push({ kind: "start", type: start[1], argument: (start[2] ?? "").trim(), ...position });
      continue;
    }
    if (END_MARKER.test(line[0])) {
      markers.push({ kind: "end", ...position });
      continue;
    }
    throw new Error(`${file}:${lineAt(text, line.index)}: the generated marker is malformed. Use ${startMarker("<type>", "<argument>")} and ${END}, each on its own line.`);
  }
  const blocks = [];
  let open = null;
  for (const marker of markers) {
    if (marker.kind === "start") {
      if (open !== null) {
        throw new Error(`${file}:${lineAt(text, marker.index)}: a generated block opens inside the block of line ${lineAt(text, open.index)}. Close the first block with ${END}.`);
      }
      open = marker;
      continue;
    }
    if (open === null) {
      throw new Error(`${file}:${lineAt(text, marker.index)}: ${END} has no start marker.`);
    }
    blocks.push({
      type: open.type,
      argument: open.argument,
      line: lineAt(text, open.index),
      contentStart: open.end,
      contentEnd: marker.index,
    });
    open = null;
  }
  if (open !== null) {
    throw new Error(`${file}:${lineAt(text, open.index)}: the generated block "${open.type}" has no ${END}.`);
  }
  return blocks;
};

/**
 * Replaces the content of each marked block with the output of `render`.
 * Text outside the blocks stays byte for byte. The content uses the line
 * ending of the file and has one blank line after the start marker and one
 * before the end marker.
 */
export const replaceBlocks = (text, render, file) => {
  const eol = text.includes("\r\n") ? "\r\n" : "\n";
  let output = "";
  let position = 0;
  for (const block of findBlocks(text, file)) {
    let content;
    try {
      content = render(block);
    } catch (error) {
      throw new Error(`${file}:${block.line}: ${error.message}`);
    }
    const body = content.replace(/\n+$/u, "").split("\n").join(eol);
    output += text.slice(position, block.contentStart);
    output += `${eol}${eol}${body}${eol}${eol}`;
    position = block.contentEnd;
  }
  return output + text.slice(position);
};

