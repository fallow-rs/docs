// Config schema

const refName = (ref) => {
  const match = ref.match(/^#\/\$defs\/(.+)$/u);
  if (match === null) {
    throw new Error(`Only local $defs references are supported: ${ref}`);
  }
  return match[1];
};

const resolveRef = (schema, node) => {
  if (node?.$ref === undefined) {
    return node;
  }
  const target = schema.$defs?.[refName(node.$ref)];
  if (target === undefined) {
    throw new Error(`The schema has no definition for ${node.$ref}.`);
  }
  return target;
};

const countRefs = (schema) => {
  const counts = new Map();
  const visit = (node) => {
    if (Array.isArray(node)) {
      node.forEach(visit);
      return;
    }
    if (node === null || typeof node !== "object") {
      return;
    }
    if (typeof node.$ref === "string") {
      counts.set(node.$ref, (counts.get(node.$ref) ?? 0) + 1);
    }
    Object.values(node).forEach(visit);
  };
  visit(schema.properties);
  visit(schema.$defs);
  return counts;
};

const isNull = (node) => node?.type === "null";

const typeOfValues = (values) => [...new Set(values.map((value) => typeof value.name))].join(" or ");

const leaf = (type, extra = {}) => ({ type, values: [], optional: false, object: null, ...extra });

/**
 * The shape of a schema node: a type label, the allowed values, whether
 * `null` is allowed, and the object whose keys the page lists below the key.
 * `refs` holds the definitions on the path, so that a recursive definition
 * stops.
 */
export const describeSchema = (schema, node, refs = []) => {
  if (node === undefined || node === true || node === null) {
    return leaf("any");
  }
  if (node.$ref !== undefined) {
    const name = refName(node.$ref);
    if (refs.includes(name)) {
      return leaf("object", { recursive: name });
    }
    return { ...describeSchema(schema, resolveRef(schema, node), [...refs, name]), ref: node.$ref };
  }
  const variants = node.anyOf ?? node.oneOf;
  if (variants !== undefined) {
    const nonNull = variants.filter((variant) => !isNull(variant));
    const optional = nonNull.length < variants.length;
    if (nonNull.length > 0 && nonNull.every((variant) => variant.const !== undefined || variant.enum !== undefined)) {
      const values = nonNull.flatMap((variant) =>
        variant.const !== undefined ? [{ name: variant.const, description: variant.description ?? null }] : variant.enum.map((name) => ({ name, description: null })),
      );
      return { ...leaf(typeOfValues(values)), values, optional };
    }
    const shapes = nonNull.map((variant) => describeSchema(schema, variant, refs));
    if (shapes.length === 1) {
      return { ...shapes[0], optional: optional || shapes[0].optional };
    }
    const withObject = shapes.find((shape) => shape.object !== null);
    return {
      type: [...new Set(shapes.map((shape) => shape.type))].join(" or "),
      values: shapes.flatMap((shape) => shape.values),
      optional,
      object: withObject?.object ?? null,
      refs: withObject?.refs ?? refs,
      itemSuffix: withObject?.itemSuffix,
    };
  }
  if (node.enum !== undefined) {
    const values = node.enum.filter((value) => value !== null).map((name) => ({ name, description: null }));
    return { ...leaf(typeOfValues(values)), values, optional: node.enum.includes(null) };
  }
  if (node.const !== undefined) {
    return { ...leaf(typeof node.const), values: [{ name: node.const, description: null }] };
  }
  const types = Array.isArray(node.type) ? node.type : node.type === undefined ? [] : [node.type];
  const optional = types.includes("null");
  const type = types.filter((entry) => entry !== "null");
  if (type.length === 1 && type[0] === "array") {
    const item = describeSchema(schema, node.items, refs);
    const label = item.type.includes(" ") ? `(${item.type})[]` : `${item.type}[]`;
    return { type: label, values: item.values, optional, object: item.object, refs: item.refs ?? refs, itemSuffix: "[]" };
  }
  if ((type.length === 1 && type[0] === "object") || (type.length === 0 && node.properties !== undefined)) {
    if (node.properties !== undefined) {
      return { ...leaf("object"), optional, object: node, refs };
    }
    if (node.additionalProperties && typeof node.additionalProperties === "object") {
      const value = describeSchema(schema, node.additionalProperties, refs);
      return { type: `map of ${value.type}`, values: value.values, optional, object: value.object, refs: value.refs ?? refs, itemSuffix: ".<key>" };
    }
    return { ...leaf("object"), optional };
  }
  return { ...leaf(type.join(" or ") || "any"), optional };
};

const constraint = (node) => {
  const parts = [];
  if (typeof node?.minimum === "number" && !(node.minimum === 0 && /^uint/u.test(node.format ?? ""))) {
    parts.push(`at least ${code(node.minimum)}`);
  }
  if (typeof node?.maximum === "number") {
    parts.push(`at most ${code(node.maximum)}`);
  }
  if (typeof node?.pattern === "string") {
    parts.push(`matches ${code(node.pattern)}`);
  }
  return parts.join(", ");
};

const defaultOf = (schema, node) => (node.default !== undefined ? node.default : resolveRef(schema, node)?.default);

// An object default repeats the defaults of its keys, which the key table
// lists. Only a scalar or an array default shows on the key itself.
const showsDefault = (value, shape) => value !== undefined && value !== null && (shape.object === null || Array.isArray(value));

const valueList = (values) =>
  values.map((entry) => (entry.description ? `- ${code(entry.name)}: ${escapeProse(entry.description.replace(/\s+/gu, " ").trim())}` : `- ${code(entry.name)}`));

/**
 * The shared enum of an object whose keys all take the same enum, such as
 * the severity of each rule in `rules`. `null` for any other object.
 */
const enumMapOf = (schema, object, refs) => {
  const children = Object.values(object.properties);
  if (children.length < ENUM_MAP_MIN_KEYS) {
    return null;
  }
  const shapes = children.map((child) => describeSchema(schema, child, refs));
  const { ref, values } = shapes[0];
  return ref !== undefined && values.length > 0 && shapes.every((shape) => shape.ref === ref) ? { ref, values } : null;
};

/**
 * An object whose keys all take one enum gets one table, and no heading for
 * each key. The values of the enum show once. An object with the keys of an
 * object that the reference already lists links to that object.
 */
const renderEnumMap = (context, { path, display, id, properties, enumMap }, out) => {
  const names = properties.map(([name]) => name);
  for (const name of names) {
    context.locations.set([...path, name].join("."), id);
  }
  const earlier = context.enumMaps.find((entry) => entry.ref === enumMap.ref && names.every((name) => entry.names.has(name)));
  if (earlier !== undefined) {
    out.push(`Each key of [${code(earlier.display)}](${earlier.link}) can appear here, with the same values.`, "");
    return;
  }
  context.enumMaps.push({ ref: enumMap.ref, names: new Set(names), display, link: `/reference/${context.page}#${id}` });
  out.push("Each key takes one of these values:", "", ...valueList(enumMap.values));
  out.push(
    "",
    ...table(
      ["Key", "Default", "Description"],
      properties.map(([name, child]) => {
        const value = defaultOf(context.schema, child);
        const text = firstSentences(replaceDashes((child.description ?? "").trim()), 1);
        return [code(name), value === undefined || value === null ? "" : cellCode(JSON.stringify(value)), escapeCell(text)];
      }),
    ),
    "",
  );
};

/**
 * Renders one config key and the keys below it. `path` is the list of key
 * names from the top level, `display` the dotted name with `[]` for array
 * items and `.<key>` for map values.
 */
const renderConfigKey = (context, { path, display, node, level, refs }, out) => {
  const { schema, refCounts, ids } = context;
  const id = anchorId(path.join("-"));
  if (ids.has(id)) {
    throw new Error(`Two config keys share the heading id "${id}": ${ids.get(id)} and ${display}.`);
  }
  ids.set(id, display);
  context.locations.set(path.join("."), id);
  const resolved = resolveRef(schema, node);
  const shape = describeSchema(schema, node, refs);
  const facts = [`- Type: ${code(shape.type)}${shape.optional ? " (optional)" : ""}`];
  const value = defaultOf(schema, node);
  if (showsDefault(value, shape)) {
    facts.push(`- Default: ${code(JSON.stringify(value))}`);
  }
  const limits = constraint(resolved) || constraint(resolved?.items);
  if (limits !== "") {
    facts.push(`- Value: ${limits}`);
  }
  const shared = shape.ref !== undefined && (refCounts.get(shape.ref) ?? 0) > SHARED_ENUM_LIMIT;
  const described = shape.values.some((entry) => entry.description);
  const listValues = shape.values.length > 0 && described && !shared;
  if (shape.values.length > 0 && !listValues) {
    facts.push(`- Allowed values: ${shape.values.map((entry) => code(entry.name)).join(", ")}`);
  }
  out.push(`${"#".repeat(Math.min(level, MAX_HEADING_LEVEL))} ${code(display)} {#${id}}`, "", ...facts, "");
  const description = node.description ?? resolved?.description;
  if (description) {
    out.push(renderDoc(description), "");
  }
  if (listValues) {
    out.push("Allowed values:", "", ...valueList(shape.values), "");
  }
  if (shape.object === null) {
    return;
  }
  const suffix = shape.itemSuffix ?? "";
  const properties = Object.entries(shape.object.properties);
  const childRefs = shape.refs ?? refs;
  const enumMap = enumMapOf(schema, shape.object, childRefs);
  if (enumMap !== null) {
    renderEnumMap(context, { path, display, id, properties, enumMap }, out);
    return;
  }
  out.push(
    ...table(
      ["Key", "Type", "Default"],
      properties.map(([name, child]) => {
        const childShape = describeSchema(schema, child, childRefs);
        const childDefault = defaultOf(schema, child);
        return [
          `[${code(name)}](#${anchorId([...path, name].join("-"))})`,
          cellCode(childShape.type),
          showsDefault(childDefault, childShape) ? cellCode(JSON.stringify(childDefault)) : "",
        ];
      }),
    ),
    "",
  );
  for (const [name, child] of properties) {
    renderConfigKey(context, { path: [...path, name], display: `${display}${suffix}.${name}`, node: child, level: level + 1, refs: childRefs }, out);
  }
};

