const frontmatter = ({ title, description, keywords, icon }) =>
  ["---", `title: ${yamlString(title)}`, `description: ${yamlString(description)}`, `keywords: ${JSON.stringify(keywords)}`, `icon: ${yamlString(icon)}`, "---"].join("\n");

/** A fully generated page: frontmatter, the generated-file note and one marked block. */
export const generatedPage = (meta, type, argument, body) =>
  [frontmatter(meta), "", GENERATED_NOTE, "", startMarker(type, argument), "", body, "", END, ""].join("\n");

const requireArgument = (block) => {
  if (block.argument === "") {
    throw new Error(`The block "${block.type}" needs an argument, for example ${startMarker(block.type, "dupes")}.`);
  }
  return block.argument;
};

/** Renders the content of one marked block of a hand-written page. */
export const renderBlock = (contract, block, { configLink } = {}) => {
  switch (block.type) {
    case "cli-options":
      return renderCliOptions(contract, requireArgument(block));
    case "cli-synopsis":
      return renderCliSynopsis(contract, requireArgument(block));
    case "cli-subcommands":
      return renderCliSubcommands(contract, requireArgument(block));
    case "cli-global-options":
      return renderGlobalOptions(contract);
    case "environment-variables":
      return renderEnvironment(contract, block.argument);
    case "rule":
      return renderRule(contract, requireArgument(block), configLink);
    default:
      throw new Error(`Unknown generated block type "${block.type}". Use cli-options, cli-synopsis, cli-subcommands, cli-global-options, environment-variables or rule.`);
  }
};

