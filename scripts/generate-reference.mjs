const newConfigContext = (schema) => ({ schema, refCounts: countRefs(schema), ids: new Map(), locations: new Map(), enumMaps: [], page: "config" });

const renderKeys = (context, keys) => {
  const out = [];
  for (const key of keys) {
    renderConfigKey(context, { path: [key], display: key, node: context.schema.properties[key], level: 2, refs: [] }, out);
  }
  return out.join("\n").replace(/\n{3,}/gu, "\n\n").trim();
};

const assignAreas = (keys) => {
  const assigned = new Map();
  for (const area of CONFIG_AREAS) {
    for (const key of area.keys) {
      if (!keys.includes(key)) {
        throw new Error(`CONFIG_AREAS names "${key}", which the config schema does not have.`);
      }
      if (assigned.has(key)) {
        throw new Error(`CONFIG_AREAS names "${key}" twice.`);
      }
      assigned.set(key, area.slug);
    }
  }
  const missing = keys.filter((key) => !assigned.has(key));
  if (missing.length > 0) {
    throw new Error(`The config keys ${missing.join(", ")} have no area. Add each to CONFIG_AREAS in ${SCRIPT}.`);
  }
  return assigned;
};

/**
 * The config reference: one page when it fits in the character limit, else
 * one page for each area of {@link CONFIG_AREAS} and an index page. Returns
 * the page bodies and a function that gives the link of a dotted config key.
 */
export const renderConfigPages = (schema, limit = PAGE_CHARACTER_LIMIT) => {
  const keys = Object.keys(schema.properties);
  const single = newConfigContext(schema);
  const body = renderKeys(single, keys);
  if (body.length + PAGE_FRAME_RESERVE <= limit) {
    return {
      split: false,
      pages: [{ slug: "config", title: "Config file", body, keys }],
      link: (dotted) => (single.locations.has(dotted) ? `/reference/config#${single.locations.get(dotted)}` : undefined),
    };
  }
  const assigned = assignAreas(keys);
  const context = newConfigContext(schema);
  const locations = new Map();
  const pages = CONFIG_AREAS.map((area) => {
    const ordered = keys.filter((key) => assigned.get(key) === area.slug);
    const before = new Set(context.locations.keys());
    context.page = `config-${area.slug}`;
    const areaBody = renderKeys(context, ordered);
    for (const [dotted, id] of context.locations) {
      if (!before.has(dotted)) {
        locations.set(dotted, `/reference/config-${area.slug}#${id}`);
      }
    }
    return { slug: `config-${area.slug}`, title: area.title, body: areaBody, keys: ordered };
  });
  return { split: true, pages, link: (dotted) => locations.get(dotted) };
};

const CONFIG_INTRO = "The config file holds the settings of fallow. [How config works](/configuration/overview) explains where fallow finds the file and how files merge.";

/** The index page of a split config reference: one row for each top-level key. */
/** The length above which a config index cell keeps only the text before a list. */
const INDEX_SUMMARY_LIMIT = 300;

/**
 * A config index cell. The first sentence of some keys introduces a long
 * list of nested keys after a colon. The cell then keeps the text before the
 * colon, because the entry of the key has the full list.
 */
export const indexSummary = (sentence) => {
  if (sentence.length <= INDEX_SUMMARY_LIMIT) {
    return sentence;
  }
  const colon = splitCode(sentence).reduce(
    (found, part, index, parts) => {
      if (found.done || part.code) {
        return { ...found, offset: found.done ? found.offset : found.offset + part.text.length };
      }
      const at = part.text.indexOf(": ");
      return at === -1 ? { ...found, offset: found.offset + part.text.length } : { done: true, offset: found.offset + at };
    },
    { done: false, offset: 0 },
  );
  return colon.done ? terminate(sentence.slice(0, colon.offset).trim()) : sentence;
};

export const renderConfigIndex = (schema, pages) => {
  const lines = [CONFIG_INTRO, ""];
  for (const page of pages) {
    lines.push(`## ${escapeProse(page.title)} {#${page.slug.replace(/^config-/u, "")}}`, "");
    const rows = page.keys.map((key) => {
      const node = schema.properties[key];
      const shape = describeSchema(schema, node);
      const summary = indexSummary(firstSentences(replaceDashes((node.description ?? resolveRef(schema, node)?.description ?? "").trim()), 1));
      return [`[${code(key)}](/reference/${page.slug}#${anchorId(key)})`, cellCode(shape.type), escapeCell(summary)];
    });
    lines.push(...table(["Key", "Type", "Description"], rows), "");
  }
  return lines.join("\n").trim();
};

