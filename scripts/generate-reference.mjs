const CODE_SPAN = /(`+)(?!`)[\s\S]*?(?<!`)\1(?!`)/gu;

/** Splits a text into code spans and prose. */
export const splitCode = (text) => {
  const parts = [];
  let last = 0;
  for (const match of text.matchAll(CODE_SPAN)) {
    if (match.index > last) {
      parts.push({ code: false, text: text.slice(last, match.index) });
    }
    parts.push({ code: true, text: match[0] });
    last = match.index + match[0].length;
  }
  if (last < text.length) {
    parts.push({ code: false, text: text.slice(last) });
  }
  return parts;
};

const mapProse = (text, map) =>
  splitCode(text)
    .map((part) => (part.code ? part.text : map(part.text)))
    .join("");

/**
 * Replaces each em dash with a comma. The docs never use an em dash, and the
 * help text of the tool sometimes has one. A spaced double hyphen outside
 * code is an em dash too.
 */
export const replaceDashes = (text) =>
  mapProse(text.replace(SPACED_EM_DASH, ", "), (prose) => prose.replace(/(?<=\S)[ \t]+--[ \t]+(?=\S)/gu, ", "))
    .replace(/,(?:[ \t]*,)+/gu, ",")
    .replace(/^,[ \t]*/u, "");

const MARKDOWN_PUNCTUATION = /\\(?=[!-/:-@[-`{-~])/gu;
const TAG = /<([A-Za-z/!][^<>\n`]*)>/gu;

const wrapTags = (prose) => prose.replace(TAG, (tag) => `\`${tag}\``);

/** A rustdoc intra-doc link, such as ``[`Type::field`]``, that is not a Markdown link. */
const RUSTDOC_LINK = /\[(`[^`\n]+`)\](?![([])/gu;
const AUTOLINK = /<(https?:\/\/[^\s<>`]+)>/gu;

/**
 * Removes the markup of the Rust doc comments that the tool text comes from.
 * A rustdoc link keeps only its code span, because its target is a Rust item
 * and not a page. An autolink such as `<https://example.com>` becomes a
 * Markdown link, so that the tag escape does not turn it into code.
 */
export const cleanToolText = (text) =>
  mapProse(text.replace(RUSTDOC_LINK, "$1"), (prose) => prose.replace(AUTOLINK, "[$1]($1)"));

const escapeCharacters = (prose) =>
  prose
    .replace(MARKDOWN_PUNCTUATION, "\\\\")
    .replace(/[<{}*]/gu, (character) => `\\${character}`);

/**
 * Makes tool text safe for MDX prose. A tag-like `<NAME>` becomes code, and a
 * bare `<`, `{`, `}` or `*` gets a backslash, because MDX reads `<` as JSX,
 * braces as an expression and `*` as emphasis. Code spans stay as they are.
 */
export const escapeProse = (text) => mapProse(mapProse(replaceDashes(cleanToolText(text)), wrapTags), escapeCharacters);

/**
 * {@link escapeProse} for a text that starts a paragraph. MDX reads a
 * paragraph that starts with `import` or `export` as a module statement, so
 * that word becomes code. A leading `#`, `>`, `+`, `-` or `1.` gets a
 * backslash, so that it does not start a heading, a quote or a list.
 */
export const escapeParagraph = (text) =>
  escapeProse(text.replace(/\s+/gu, " ").trim())
    .replace(/^(import|export)(?=\s)/u, "`$1`")
    .replace(/^([#>+-]|\d+\.)/u, "\\$1");

/** {@link escapeProse} for a table cell: one line, and each `|` escaped, also in code. */
export const escapeCell = (text) =>
  escapeProse(text.replace(/\s+/gu, " ").trim()).replace(/(?<!\\)\|/gu, "\\|");

/** The text with terminal punctuation, so that a second sentence can follow. */
const terminate = (text) => (text === "" || /(?:[.!?:]|[.!?]\))$/u.test(text) ? text : `${text}.`);

const ABBREVIATION = /(?:\b(?:e\.g|i\.e|etc|vs|cf|approx|incl|No)|\.\.)$/u;

/**
 * Splits a text into sentences. A sentence ends at `.`, `!` or `?` before a
 * space and a capital letter, a parenthesis, a quote or a code span. A
 * sentence in parentheses ends at its `)`. Code spans and abbreviations such
 * as "e.g." do not end a sentence.
 */
export const splitSentences = (text) => {
  const masked = splitCode(text)
    .map((part) => (part.code ? `\`${"x".repeat(part.text.length - 2)}\`` : part.text))
    .join("");
  const result = [];
  let start = 0;
  for (const match of masked.matchAll(/[.!?](?=\s+[A-Z(`"'[])|\)(?=\s+[A-Z])/gu)) {
    const before = masked.slice(start, match.index);
    if (match[0] === ")" ? !before.trimStart().startsWith("(") : ABBREVIATION.test(before)) {
      continue;
    }
    result.push(text.slice(start, match.index + 1).trim());
    start = match.index + 1;
  }
  const rest = text.slice(start).trim();
  if (rest !== "") {
    result.push(rest);
  }
  return result;
};

/**
 * The first `count` sentences of a text. A sentence in parentheses, such as
 * "(defaults to `5`)", does not count, and the parenthesized sentences right
 * after the last counted sentence stay.
 */
export const firstSentences = (text, count = 2) => {
  const kept = [];
  let counted = 0;
  const all = text
    .split(/\n[ \t]*\n/u)
    .flatMap((paragraph) => splitSentences(paragraph.replace(/\s+/gu, " ").trim()));
  for (const sentence of all) {
    const parenthesized = sentence.startsWith("(");
    if (counted === count && !parenthesized) {
      break;
    }
    kept.push(sentence);
    if (!parenthesized) {
      counted += 1;
    }
  }
  return kept
    .map((sentence, index) => (index < kept.length - 1 ? terminate(sentence) : sentence))
    .join(" ")
    .replace(/\.{2,}$/u, ".");
};

const code = (value) => {
  const text = String(value);
  const ticks = text.includes("`") ? "``" : "`";
  const pad = text.startsWith("`") || text.endsWith("`") ? " " : "";
  return `${ticks}${pad}${text}${pad}${ticks}`;
};

const cellCode = (value) => code(value).replace(/\|/gu, "\\|");

const table = (headers, rows) => [
  `| ${headers.join(" | ")} |`,
  `|${headers.map(() => ":--").join("|")}|`,
  ...rows.map((row) => `| ${row.join(" | ")} |`),
];


/**
 * Doc comments in the config schema are Markdown with hard line breaks. This
 * joins the lines of each paragraph and list item, keeps fenced code, and
 * turns a heading into a bold line, so that it does not break the outline of
 * the page.
 */
export const renderDoc = (text) => {
  const blocks = [];
  let current = null;
  let fence = null;
  const flush = () => {
    if (current !== null) {
      blocks.push(current);
      current = null;
    }
  };
  for (const line of text.split("\n")) {
    if (fence !== null) {
      fence.lines.push(line);
      if (/^\s*```\s*$/u.test(line)) {
        blocks.push(fence);
        fence = null;
      }
      continue;
    }
    if (/^\s*```/u.test(line)) {
      flush();
      fence = { kind: "fence", lines: [line.trim()] };
      continue;
    }
    if (line.trim() === "") {
      flush();
      continue;
    }
    const heading = line.match(/^\s*#{1,6}\s+(.*)$/u);
    if (heading) {
      flush();
      blocks.push({ kind: "heading", text: heading[1].trim() });
      continue;
    }
    const item = line.match(/^\s*(?:[-*]|\d+\.)\s+(.*)$/u);
    if (item) {
      flush();
      current = { kind: "item", text: item[1].trim() };
      continue;
    }
    if (current === null) {
      current = { kind: "paragraph", text: line.trim() };
    } else {
      current.text += ` ${line.trim()}`;
    }
  }
  flush();
  if (fence !== null) {
    fence.lines.push("```");
    blocks.push(fence);
  }
  const lines = [];
  blocks.forEach((block, index) => {
    const previous = blocks[index - 1];
    if (index > 0 && !(block.kind === "item" && previous.kind === "item")) {
      lines.push("");
    }
    if (block.kind === "fence") {
      lines.push(...block.lines.map((line) => line.replaceAll(EM_DASH, ",")));
    } else if (block.kind === "heading") {
      lines.push(`**${escapeProse(block.text)}**`);
    } else if (block.kind === "item") {
      lines.push(`- ${escapeProse(block.text)}`);
    } else {
      lines.push(escapeParagraph(block.text));
    }
  });
  return lines.join("\n");
};

/** A heading id: lowercase letters, digits and hyphens. */
export const anchorId = (text) =>
  text
    .toLowerCase()
    .replace(/[^a-z0-9]+/gu, "-")
    .replace(/^-+|-+$/gu, "");

