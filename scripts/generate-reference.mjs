const readJson = async (path) => JSON.parse(await readFile(resolve(ROOT, path), "utf8"));

const readIfExists = async (path) => {
  try {
    return await readFile(resolve(ROOT, path), "utf8");
  } catch (error) {
    if (error.code === "ENOENT") {
      return undefined;
    }
    throw error;
  }
};

const listDirectory = async (directory) => {
  try {
    return await readdir(resolve(ROOT, directory));
  } catch (error) {
    if (error.code === "ENOENT") {
      return [];
    }
    throw error;
  }
};

/** The generated files and the hand-written pages with blocks, each with its current and expected text. */
const plan = async () => {
  const contract = await readJson(CLI_CONTRACT);
  const schema = await readJson(CONFIG_CONTRACT);
  const inbound = await readJson(INBOUND_FILE);
  const rulePages = (await listDirectory("rules")).filter((name) => name.endsWith(".mdx")).map((name) => `rules/${name}`);
  const current = new Map(await Promise.all(rulePages.map(async (path) => [path, await readIfExists(path)])));
  const { files, config } = buildGeneratedFiles({ contract, schema, inbound, existing: (path) => current.get(path) });
  const entries = [];
  for (const [path, expected] of files) {
    entries.push({ path, expected, actual: await readIfExists(path), whole: true });
  }
  const orphans = rulePages.filter((path) => !files.has(path));
  for (const name of await listDirectory("reference")) {
    const path = `reference/${name}`;
    if (/^config(?:-[\w-]+)?\.mdx$/u.test(name) && !files.has(path)) {
      orphans.push(path);
    }
  }
  for (const path of listPagePaths(ROOT)) {
    if (files.has(path)) {
      continue;
    }
    const text = await readFile(resolve(ROOT, path), "utf8");
    if (!text.includes("generated:")) {
      continue;
    }
    checkEnvironmentBlocks(contract, text, path);
    const expected = replaceBlocks(text, (block) => renderBlock(contract, block, { configLink: config.link }), path);
    entries.push({ path, expected, actual: text, whole: false });
  }
  return { entries, orphans };
};

const inScope = (path, scopes) =>
  scopes.length === 0 || scopes.some((scope) => {
    const clean = scope.replace(/\/+$/u, "");
    return path === clean || path.startsWith(`${clean}/`);
  });

const reportOrphans = (orphans) => {
  for (const path of orphans) {
    console.error(`${path}: no issue type or config area of the contract generates this page. Remove it, or add a redirect.`);
  }
  if (orphans.length > 0) {
    process.exitCode = 1;
  }
};

/** Rule pages whose generated part alone is longer than the line budget of a rule page. */
export const overBudgetRules = (files) =>
  [...files]
    .filter(([path]) => path.startsWith("rules/"))
    .map(([path, text]) => ({ path, lines: text.slice(0, text.indexOf(END) + END.length).split("\n").length }))
    .filter((entry) => entry.lines > RULE_LINE_BUDGET);

const reportRuleBudget = (entries) => {
  for (const entry of overBudgetRules(entries.map((item) => [item.path, item.expected]))) {
    console.warn(`${entry.path}: the generated part has ${entry.lines} lines. The budget of a rule page is ${RULE_LINE_BUDGET}.`);
  }
};

const write = async (scopes) => {
  const { entries, orphans } = await plan();
  let written = 0;
  for (const entry of entries) {
    if (entry.expected === entry.actual || !inScope(entry.path, scopes)) {
      continue;
    }
    await mkdir(dirname(resolve(ROOT, entry.path)), { recursive: true });
    await writeFile(resolve(ROOT, entry.path), entry.expected);
    written += 1;
  }
  console.log(`Wrote ${written} files. The other ${entries.length - written} files were current or out of scope.`);
  reportOrphans(orphans);
  reportRuleBudget(entries);
};

const check = async () => {
  const { entries, orphans } = await plan();
  const stale = entries.filter((entry) => entry.expected !== entry.actual);
  for (const entry of stale) {
    const what = entry.actual === undefined ? "is missing" : entry.whole ? "is stale" : "has stale generated blocks";
    console.error(`${entry.path}: ${what}.`);
  }
  reportOrphans(orphans);
  if (stale.length > 0) {
    console.error("Run npm run docs:reference:write and commit the result.");
    process.exitCode = 1;
    return;
  }
  if (orphans.length === 0) {
    console.log(`The generated reference is current (${entries.length} files).`);
  }
};

/**
 * The coverage of the command pages: for each command of the contract, the
 * page that documents it and the blocks that the page has.
 */
export const coverageRows = (contract, pageText) => {
  const rows = [];
  for (const command of indexCommands(contract).values()) {
    if (command.hidden) {
      continue;
    }
    const page = command.root ? "cli/index.mdx" : `cli/${command.path.split(" ")[0]}.mdx`;
    const text = pageText(page);
    const has = (type) => text !== undefined && text.includes(startMarker(type, command.path));
    rows.push({
      command: command.path,
      page: text === undefined ? "missing" : page,
      options: has("cli-options"),
      synopsis: has("cli-synopsis"),
      subcommands: (command.subcommands ?? []).some((sub) => !sub.hidden) ? has("cli-subcommands") : null,
    });
  }
  return rows;
};

const report = async () => {
  const contract = await readJson(CLI_CONTRACT);
  const pages = new Map();
  for (const path of listPagePaths(ROOT)) {
    if (path.startsWith("cli/")) {
      pages.set(path, await readFile(resolve(ROOT, path), "utf8"));
    }
  }
  const mark = (value) => (value === null ? "n/a" : value ? "yes" : "no");
  console.log("| Command | Page | cli-options | cli-synopsis | cli-subcommands |");
  console.log("|:--|:--|:--|:--|:--|");
  for (const row of coverageRows(contract, (path) => pages.get(path))) {
    console.log(`| ${row.command} | ${row.page} | ${mark(row.options)} | ${mark(row.synopsis)} | ${mark(row.subcommands)} |`);
  }
  const global = pages.get("cli/global-flags.mdx");
  const state = global === undefined ? "missing" : global.includes(startMarker("cli-global-options")) ? "has the cli-global-options block" : "has no cli-global-options block";
  console.log(`\ncli/global-flags.mdx: ${state}`);
};

const FALLOW_ENV = { ...process.env, NO_COLOR: "1", FALLOW_TELEMETRY: "0", SKIP_FALLOW_AGENT_GUARD: "1" };
const SCHEMA_OUTPUT_LIMIT = 64 * 1024 * 1024;

const withNewline = (text) => (text.endsWith("\n") ? text : `${text}\n`);

/**
 * Refreshes the contract files. A binary runs the two schema commands. A
 * directory is a fallow checkout, which holds `docs/cli-reference.json` and
 * `schema.json`.
 */
const updateContracts = async (source) => {
  const path = resolve(source);
  if (!existsSync(path)) {
    throw new Error(`${source} does not exist. Pass a fallow binary or a fallow checkout.`);
  }
  let cli;
  let config;
  if (statSync(path).isDirectory()) {
    const read = async (name) => {
      const file = join(path, name);
      if (!existsSync(file)) {
        throw new Error(`${file} does not exist. Pass a fallow binary instead, and the generator runs the schema commands.`);
      }
      return readFile(file, "utf8");
    };
    cli = await read("docs/cli-reference.json");
    config = await read("schema.json");
  } else {
    const run = (args) => execFileSync(path, args, { encoding: "utf8", env: FALLOW_ENV, maxBuffer: SCHEMA_OUTPUT_LIMIT });
    cli = run(["schema", "--cli-reference"]);
    config = run(["config-schema"]);
  }
  const contract = JSON.parse(cli);
  JSON.parse(config);
  await mkdir(resolve(ROOT, "contracts"), { recursive: true });
  await writeFile(resolve(ROOT, CLI_CONTRACT), withNewline(cli));
  await writeFile(resolve(ROOT, CONFIG_CONTRACT), withNewline(config));
  await writeFile(resolve(ROOT, CONTRACT_README), renderContractReadme(contract));
  console.log(`Wrote the contracts of fallow ${contract.version}. Run npm run docs:reference:write next.`);
};

