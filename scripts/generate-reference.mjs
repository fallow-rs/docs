/** Parses the command-line arguments. Throws on an unknown flag. */
export const parseArguments = (args) => {
  const result = { mode: "write", scopes: [], source: null };
  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (arg === "--check" || arg === "--report" || arg === "--help") {
      result.mode = arg.slice(2);
      continue;
    }
    if (arg === "--update-contracts") {
      const value = args[index + 1];
      if (value === undefined || value.startsWith("--")) {
        throw new Error("--update-contracts needs a path to a fallow binary or a fallow checkout.");
      }
      result.mode = "update-contracts";
      result.source = value;
      index += 1;
      continue;
    }
    if (arg.startsWith("--")) {
      throw new Error(`Unknown argument: ${arg}. Use --check, --report, --update-contracts <path> or --help.`);
    }
    result.scopes.push(arg);
  }
  if (result.scopes.length > 0 && result.mode !== "write") {
    throw new Error("A path limits only the write mode.");
  }
  return result;
};

const run = async () => {
  const args = parseArguments(process.argv.slice(2));
  switch (args.mode) {
    case "help":
      console.log(HELP);
      return;
    case "check":
      await check();
      return;
    case "report":
      await report();
      return;
    case "update-contracts":
      await updateContracts(args.source);
      return;
    default:
      await write(args.scopes);
  }
};

